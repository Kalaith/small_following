def main() -> int:
    song = song_data.load()
    errors = song_data.validate(song)
    if errors:
        print("\n".join("ERROR: " + e for e in errors))
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = []
    labels = {shot["plate"]: shot.get("label", "") for shot in song["shots"] if "plate" in shot}
    for index, plate in enumerate(song["plates"]):
        rng = np.random.default_rng([SEED, index])
        if plate in POSTCARDS:
            if "NOT BUILT" not in labels.get(plate, ""):
                print(f"ERROR: {plate} is a future idea but its shot is not labelled NOT BUILT")
                return 1
            image = postcard(plate, rng)
            source = POSTCARDS[plate][2]
        elif plate in OTHER:
            image = OTHER[plate](rng)
            source = "music video plate"
        else:
            print(f"ERROR: no painter for plate {plate!r}")
            return 1
        path = OUT / f"{plate}.png"
        image.convert("RGB").save(path, optimize=True)
        manifest.append({"plate": plate, "file": path.name, "label": labels.get(plate, ""),
                         "stamp": STAMP if plate in POSTCARDS else ("DAYDREAM" if plate == "vision-enormous" else ""),
                         "source": source})
        print(f"{path.name}: {image.width}x{image.height}  {manifest[-1]['stamp'] or '-'}  ({source})")
    (OUT / "plates.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
