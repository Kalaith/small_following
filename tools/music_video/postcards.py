def canvas() -> tuple[Image.Image, Pen]:
    image = Image.fromarray(backdrop_array()).resize((W * SS, H * SS), Image.NEAREST).convert("RGBA")
    return image, Pen(image, SS)


def backdrop_array() -> np.ndarray:
    """The promo's dark lilac backdrop (tools/promo/render_promo.py), as an array."""
    y, x = np.mgrid[0:H, 0:W]
    glow = np.clip(1 - np.sqrt(((x - 960) / 1200) ** 2 + ((y - 480) / 800) ** 2), 0, 1)
    a = np.zeros((H, W, 3), dtype=np.uint8)
    for c, (base, lift) in enumerate([(17, 17), (11, 10), (28, 26)]):
        a[:, :, c] = base + lift * glow
    im = Image.fromarray(a)
    d = ImageDraw.Draw(im)
    for radius in (360, 470, 620, 780, 950):
        d.ellipse((960 - radius, 540 - radius, 960 + radius, 540 + radius), outline="#34213e", width=1)
    rng = np.random.default_rng(73)
    for _ in range(90):
        px, py = rng.integers(0, W), rng.integers(0, H)
        d.ellipse((px, py, px + 2, py + 2), fill="#634c74")
    return np.asarray(im)


def frame_pen(pen: Pen) -> Pen:
    """A fresh frame-space pen; sprite helpers move a shared pen's origin."""
    return Pen(pen.image, pen.ss).at(0, 0, 1)


def seal_border(pen: Pen, box, color=LILAC, ink=INK) -> None:
    x0, y0, x1, y1 = box
    p = frame_pen(pen)
    for inset, width, col in ((20, 3, ink), (32, 2, color)):
        p.line((x0 + inset, y0 + inset), (x1 - inset, y0 + inset), col, width)
        p.line((x1 - inset, y0 + inset), (x1 - inset, y1 - inset), col, width)
        p.line((x1 - inset, y1 - inset), (x0 + inset, y1 - inset), col, width)
        p.line((x0 + inset, y1 - inset), (x0 + inset, y0 + inset), col, width)
    for cx, cy in ((x0 + 26, y0 + 26), (x1 - 26, y0 + 26), (x0 + 26, y1 - 26), (x1 - 26, y1 - 26)):
        p.circle((cx, cy), 15, PARCHMENT)
        p.ring((cx, cy), 14, ink, 2)
        star = [(cx + 10 * math.cos(-math.pi / 2 + k * 4 * math.pi / 5),
                 cy + 10 * math.sin(-math.pi / 2 + k * 4 * math.pi / 5)) for k in range(6)]
        for a, b in zip(star, star[1:]):
            p.line(a, b, color, 1.5)


def paper(image: Image.Image, box, rng, tone=PARCHMENT) -> None:
    """A parchment card with a soft shadow and seeded fibres."""
    x0, y0, x1, y1 = [v * SS for v in box]
    shadow = Image.new("RGBA", image.size, (0, 0, 0, 0))
    ImageDraw.Draw(shadow).rounded_rectangle((x0 + 18, y0 + 24, x1 + 18, y1 + 24), 12 * SS, fill=(5, 2, 10, 150))
    image.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(18 * SS)))
    d = ImageDraw.Draw(image, "RGBA")
    d.rounded_rectangle((x0, y0, x1, y1), 10 * SS, fill=tone)
    for _ in range(900):
        px, py = rng.uniform(x0, x1), rng.uniform(y0, y1)
        length = rng.uniform(3, 14) * SS
        angle = rng.uniform(0, math.pi)
        d.line((px, py, px + length * math.cos(angle), py + length * math.sin(angle)),
               fill=(120, 90, 60, int(rng.uniform(10, 28))), width=SS)


def stamp(image: Image.Image, text: str, centre, angle: float, rng, color=(164, 52, 72),
          size: int = 40) -> None:
    """A worn rubber stamp, rotated, with seeded ink gaps."""
    face = font(size * SS, serif=False, bold=True)
    probe = ImageDraw.Draw(image)
    tw = probe.textlength(text, font=face)
    pad = 26 * SS
    w, h = int(tw + 2 * pad), int(size * 2.5 * SS)
    layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    ink = color + (225,)
    d.rounded_rectangle((4 * SS, 4 * SS, w - 4 * SS, h - 4 * SS), 10 * SS, outline=ink, width=5 * SS)
    d.rounded_rectangle((13 * SS, 13 * SS, w - 13 * SS, h - 13 * SS), 6 * SS, outline=ink, width=2 * SS)
    d.text((w / 2, h / 2), text, font=face, fill=ink, anchor="mm")
    alpha = np.asarray(layer.getchannel("A")).astype(np.float32)
    worn = rng.uniform(.55, 1.0, (h // (3 * SS) + 1, w // (3 * SS) + 1))
    worn = np.kron(worn, np.ones((3 * SS, 3 * SS)))[:h, :w]
    layer.putalpha(Image.fromarray((alpha * worn).astype(np.uint8)))
    # A clean cream label behind the worn ink keeps the stamp legible on dark scenes.
    label = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(label).rounded_rectangle((4 * SS, 4 * SS, w - 4 * SS, h - 4 * SS), 10 * SS,
                                            fill=(246, 236, 214, 235))
    label.alpha_composite(layer)
    layer = label
    layer = layer.rotate(angle, expand=True, resample=Image.BICUBIC)
    image.alpha_composite(layer, (int(centre[0] * SS - layer.width / 2), int(centre[1] * SS - layer.height / 2)))


