def postcard(plate: str, rng) -> Image.Image:
    place, subtitle, source = POSTCARDS[plate]
    image, pen = canvas()
    card = (210, 95, 1710, 985)
    paper(image, card, rng)
    seal_border(pen, card)
    p = frame_pen(pen)
    p.text((960, 200), place, 76, INK, serif=True, bold=True)
    p.text((960, 268), subtitle, 30, "#6b4f7a", serif=True)
    x0, y0, x1, y1 = SCENE
    d = ImageDraw.Draw(image, "RGBA")
    scene = Image.new("RGBA", ((x1 - x0) * SS, (y1 - y0) * SS))
    SCENES[plate](Pen(scene, SS).at(0, 0, 1), scene, x1 - x0, y1 - y0, rng)
    mask = Image.new("L", scene.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, scene.width - 1, scene.height - 1), 14 * SS, fill=255)
    image.paste(scene, (x0 * SS, y0 * SS), mask)
    d.rounded_rectangle((x0 * SS, y0 * SS, x1 * SS, y1 * SS), 14 * SS, outline=INK, width=3 * SS)
    p.text((960, 862), "A POSTCARD FROM SOMEDAY", 22, "#6b4f7a", serif=False, bold=True)
    p.text((960, 905), f"From the design notes ({source}). Not a promise.", 21, "#5a4a52", serif=False)
    stamp(image, STAMP, (1395, 372), 6, rng, size=32)
    return finish(image, SS)


def _sky(pen, w, h, top, bottom, ground, horizon=.62):
    d = pen.draw
    for i in range(h * SS):
        t = i / (h * SS)
        c = tuple(int(a + (b - a) * t) for a, b in zip(_rgb(top), _rgb(bottom)))
        d.line((0, i, w * SS, i), fill=c)
    d.rectangle((0, int(h * horizon * SS), w * SS, h * SS), fill=ground)


def _rgb(hex_):
    hex_ = hex_.lstrip("#")
    return tuple(int(hex_[i:i + 2], 16) for i in (0, 2, 4))


